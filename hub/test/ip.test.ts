import { describe, expect, it } from 'vitest';
import { isPublicIp } from '../src/probe';

describe('isPublicIp', () => {
  it.each(['8.8.8.8', '1.1.1.1', '93.184.216.34', '172.32.0.1', '2606:4700:4700::1111'])('%s é pública', (ip) => {
    expect(isPublicIp(ip)).toBe(true);
  });
  it.each(['0.0.0.1', '10.1.2.3', '100.64.0.1', '127.0.0.1', '169.254.1.1', '172.16.0.1', '172.31.255.255', '192.0.0.1', '192.0.2.1',
    '192.168.1.1', '198.18.0.1', '198.51.100.1', '203.0.113.7', '224.0.0.1', '240.0.0.1', '255.255.255.255',
    '::', '::1', 'fc00::1', 'fd12::1', 'fe80::1', 'ff02::1', '64:ff9b::1.2.3.4', '2001:db8::1', '::ffff:10.0.0.1', 'lixo'])('%s não é pública', (ip) => {
    expect(isPublicIp(ip)).toBe(false);
  });
});
